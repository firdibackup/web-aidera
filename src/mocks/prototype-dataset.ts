function buildArtifacts(card: RawContentCard): unknown[] {
  return artifactPipeline.slice(0, card.artifact_count).map((entry, index) => ({
    id: card.id * 100 + index + 1,
    content_id: card.id,
    type: entry.type,
    title: `${entry.label} v1 · ${card.code}`,
    version: 1,
    path: `${card.code}/${entry.type}-v1.md`,
    summary: `Prototype Data: contoh ${entry.label.toLowerCase()} untuk ${card.code}.`,
    body: [
      `# ${entry.label} · ${card.code}`,
      "",
      "Prototype Data — tidak tersimpan permanen.",
      "",
      `Dokumen contoh untuk "${card.title}".`,
      `Pilar: ${card.pillar}.`,
      `Hook: ${card.hook}`,
    ].join("\n"),
    created_by: "Prototype fixture",
    created_at: "2026-09-13T08:00:00+07:00",
    data_source: source,
  }));
}

function buildTasks(card: RawContentCard): unknown[] {
  const agent = stageAgents[card.stage] ?? null;

  if (!agent) {
    return [];
  }

  const blocked = card.stage === "blocked" || card.active_run_status === "blocked";

  return [
    {
      id: card.id * 10 + 1,
      content_id: card.id,
      stage: card.stage,
      agent,
      status: blocked ? "blocked" : "queued",
      attempts: blocked ? 2 : 0,
      max_attempts: 2,
      error_summary: blocked
        ? "Prototype Data: contoh task berhenti karena sumber primer belum tersedia."
        : null,
      created_at: "2026-09-13T08:00:00+07:00",
      updated_at: "2026-09-13T10:10:00+07:00",
      data_source: source,
    },
  ];
}

function enrichContents(cards: RawContentCard[]): unknown[] {
  return cards.map((card) => {
    const extras = contentExtras[card.id] ?? {};
    const artifacts = buildArtifacts(card);

    return {
      ...card,
      summary: extras.summary ?? `Prototype Data: ringkasan contoh untuk ${card.code}.`,
      objective: extras.objective ?? "Save",
      cta_concept: extras.cta_concept ?? "Simpan untuk dipakai pada workflow berikutnya.",
      plan_id: extras.plan_id ?? null,
      archived: false,
      artifacts,
      tasks: buildTasks(card),
      approvals: prototypeApprovals
        .filter((approval) => approval.target_type === "content" && approval.target_id === card.id)
        .map((approval) => ({
          id: approval.id,
          type: approval.type,
          status: approval.status,
          title: approval.title,
          requester: approval.requester,
          requested_at: approval.requested_at,
          decided_at: approval.decided_at,
          data_source: source,
        })),
      activity: prototypeActivities.filter(
        (activity) => activity.target_type === "content" && activity.target_id === card.id,
      ),
      metrics: null,
      final_package_artifact_id:
        card.artifact_count >= artifactPipeline.length
          ? card.id * 100 + artifactPipeline.length
          : null,
    };
  });
}

